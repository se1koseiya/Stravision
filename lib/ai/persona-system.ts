/** 默认 persona */
export const DEFAULT_PERSONA: PersonaId = 'expert'

/**
 * 获取 persona 的完整 prompt 注入（systemPromptExtension + styleConstraints + decisionBias）
 * 注：注入位置在 system prompt 开头（提高优先级），由调用方决定
 */
export function getPersonaPrompt(personaId?: string): string {
  const id = (personaId && personaId in PERSONAS ? personaId : DEFAULT_PERSONA) as PersonaId
  const p = PERSONAS[id]
  return `\n\n${p.systemPromptExtension}\n\n${p.styleConstraints}\n\n${p.decisionBias}\n\n**⚠️ 重要：以上角色身份优先级最高，必须严格执行其输出格式和禁用项。即使用户问题很简单，也要保持该角色的语气和结构。**`
}

/**
 * 获取 persona 元信息（供前端 UI 使用）
 */
export function getPersonaMeta(personaId?: string): Omit<Persona, 'systemPromptExtension' | 'styleConstraints' | 'decisionBias'> {
  const id = (personaId && personaId in PERSONAS ? personaId : DEFAULT_PERSONA) as PersonaId
  const p = PERSONAS[id]
  return { id: p.id, name: p.name, tagline: p.tagline, iconName: p.iconName, color: p.color }
}

/**
 * 获取所有 persona 元信息列表（供前端切换 UI 使用）
 */
export function listPersonas() {
  return Object.values(PERSONAS).map(p => ({
    id: p.id,
    name: p.name,
    tagline: p.tagline,
    iconName: p.iconName,
    color: p.color,
  }))
}
