/**
 * 输出 JSON 契约（作为文本注入提示词，不用 function-calling：
 * 多数视觉模型对 function-calling + image 同时使用支持不稳，
 * 而纯文本 JSON 契约 + 服务端强校验更可靠）。
 */
export const DIAGNOSIS_OUTPUT_CONTRACT = `{
  "summary": "一句话结论（40 字以内，说清「部位 + 程度 + 典型表现」，直接写给种植户看）",
  "diseaseName": "最可能的病名（中文，如「白粉病」「红蜘蛛」；信息不足时填「信息不足」）",
  "category": "fungal | bacterial | viral | pest | physiological | nutrient | unknown",
  "confidence": 0.0,
  "severity": "none | mild | moderate | severe",
  "affectedParts": ["叶片", "果实"],
  "analysis": [
    { "label": "叶片表现", "value": "该维度下的具体观察（≤30 字）" },
    { "label": "病斑特征", "value": "该维度下的具体观察（≤30 字）" },
    { "label": "颜色与边界", "value": "该维度下的具体观察（≤30 字）" }
  ],
  "evidence": ["图中所见的具体形态依据，1~3 条，必须可核对"],
  "candidates": [
    { "name": "最可能的病名（与 diseaseName 一致）", "probability": 0.6, "note": "为什么最可能是它（≤40 字）" },
    { "name": "第二可能", "probability": 0.2, "note": "为什么可能是它 / 为什么排第二（≤40 字）" },
    { "name": "第三可能", "probability": 0.1, "note": "（≤40 字）" }
  ],
  "differentials": [
    { "name": "其他候选病名", "excluded": true, "reason": "排除或无法排除的理由" }
  ],
  "treatments": [
    { "level": "environment", "label": "环境调控", "actions": ["具体操作"] },
    { "level": "physical", "label": "物理防治", "actions": ["具体操作"] },
    { "level": "biological", "label": "生物防治", "actions": ["具体操作"] },
    { "level": "chemical", "label": "化学防治", "actions": ["药剂名+浓度"], "safetyIntervalDays": 7 }
  ],
  "followUp": ["若需要补拍，写清楚拍哪个部位、什么角度；无需补拍时为空数组"],
  "detections": [
    { "label": "病斑", "labelKey": "lesion", "confidence": 0.0, "bbox": { "x": 0.1, "y": 0.2, "w": 0.3, "h": 0.25 } }
  ]
}`

export interface BuildDiagnosisPromptOptions {
    /** 上传图片张数（用于提示模型可对照多图） */
    imageCount?: number
    /** 用户补充的场景上下文 */
    context?: string
    /**
     * 是否要求模型给出 bbox 定位。
     * 默认 true —— 前端会把它渲染成「检测框 + 扫描」的视觉反馈；
     * 若上游模型 grounding 能力弱，可关掉以节省输出 token。
     */
    withBoundingBoxes?: boolean
}

/**
 * 组装用户提示词。
 *
 * 把「输出契约」放在最后（模型对末尾指令的遵循度最高），
 * 并把上下文自然语言化，避免模型把它当成必须逐条回答的问题。
 */
export function buildDiagnosisPrompt(options: BuildDiagnosisPromptOptions = {}): string {
    const { imageCount = 1, context, withBoundingBoxes = true } = options

    const parts: string[] = []

    parts.push(
        imageCount > 1
            ? `以下是同一批草莓植株的 ${imageCount} 张照片（可能包含全株远景与病部特写），请综合判断。`
            : `以下是用户拍摄的草莓照片，请诊断。`
    )

    if (context && context.trim()) {
        parts.push(`用户补充的信息：${context.trim()}`)
    }

    parts.push(`请按以下 JSON 结构返回诊断结果（只输出 JSON，不要任何额外文字、不要 markdown 代码块）：`)
    parts.push(DIAGNOSIS_OUTPUT_CONTRACT)

    parts.push(`填写要求：`)
    parts.push(`- confidence 为 0~1 的小数，必须反映真实把握程度，不要习惯性给 0.9。`)
    parts.push(`- analysis 固定给 3 行，label 用「叶片表现 / 病斑特征 / 颜色与边界」这类**观察维度**，value 写图中该维度的具体结果；看不清的维度写「图中无法判断」，不要编。`)
    parts.push(`- evidence 只能写图中**真实可见**的形态特征（如"叶背有白色粉状覆盖物，约占叶面积三成"）。`)
    parts.push(`- candidates 给 2~3 个按可能性降序，第一条必须与 diseaseName 相同；probability 之和不必等于 1，但必须**单调不增**且反映真实把握；note 写"为什么可能是它"。`)
    parts.push(`- differentials 至少 2 条，覆盖"最容易与主诊断混淆"的候选，并写明支持或排除的理由。`)
    parts.push(`- treatments 按 环境调控 → 物理防治 → 生物防治 → 化学防治 的顺序给出，不适用的层级可省略；给出 chemical 时必须带 safetyIntervalDays。`)
    parts.push(`- 若图片不足以支撑结论：diseaseName 填「信息不足」，confidence 调低，并在 followUp 里明确该补拍什么。`)

    // 🔥 长度约束：诊断 JSON 字段多，模型很容易写成长篇小作文 → 输出被 max_tokens
    //    截断在 JSON 中途 → 整份结果作废（实测 deepseek-flash 就这么失败过）。
    //    这里给出明确字数上限，保证 JSON 能在预算内闭合。
    parts.push(
        `- ⚠️ 输出必须简短，整份 JSON **不超过 2000 个字符**：` +
            `analysis 每行 value ≤ 30 字；evidence 最多 3 条、每条 ≤ 60 字；` +
            `candidates 最多 3 条、每条 note ≤ 40 字；differentials 只给 2 条、每条 reason ≤ 50 字；` +
            `每个防治层级的 actions 最多 2 条、每条 ≤ 30 字；followUp 最多 2 条。` +
            `宁可精简，也不要写到一半被截断。`,
    )

    if (withBoundingBoxes) {
        parts.push(
            `- detections：用归一化坐标（0~1，相对图片左上角）框出图中异常区域，` +
            `bbox 形如 {"x":0.1,"y":0.2,"w":0.3,"h":0.25}；最多 6 个，按置信度降序；` +
            `无法定位时返回空数组 []。` +
            `⚠️ bbox 必须**紧贴病灶的可见边界**（只要病斑本身，不要把整片叶/整张图框进去），` +
            `宽高一般不超过整图的 1/2；多个相邻小病斑可以合成一个框，但不要合并到不同部位。`
        )
    } else {
        parts.push(`- detections 固定返回空数组 []。`)
    }

    parts.push(`再次强调：只输出一个 JSON 对象。`)

    return parts.join('\n')
}
