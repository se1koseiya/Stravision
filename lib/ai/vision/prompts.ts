/**
 * 病虫害视觉诊断 —— 提示词资产
 *
 * 这个文件是「诊断准确率」的第一道防线。
 *
 * 为什么不能只说一句"看看这是什么病"？
 * 通用视觉模型在细粒度农业病害上会**退化成泛泛而谈的散文**，且极易产生幻觉
 * （把生理性缺素说成真菌病害，是典型错误）。
 *
 * 因此这里的提示词做了四件硬约束：
 *   1. **强制结构化输出** —— 不允许散文，必须按 schema 出 JSON；
 *   2. **强制 evidence（图中依据）** —— 有依据可核对，幻觉无处藏身；
 *   3. **强制 differentials（鉴别排除）** —— 迫使模型做鉴别诊断而非直接断言；
 *   4. **强制 followUp（补拍建议）** —— 看不清时允许说"看不清"，而不是硬编一个病名。
 *
 * 先验清单（STRAWBERRY_DISEASE_PRIORS）来自平台已有的种植知识沉淀
 * （见 components/ai/farm-skills.tsx 的病虫害胶囊），是草莓场景的经验资产。
 */

